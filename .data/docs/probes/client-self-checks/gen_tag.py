"""Emit straight-line HalfSipHash tag functions for the U2 probe.

Each variant has its compression rounds c, finalization rounds d and six rotation amounts as
literals, as a build would emit them. Writes tag_<c><d>_<name>.luau beside this script.

Usage: python3 -I gen_tag.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REFERENCE = (5, 16, 8, 7, 13, 16)  # veorq/SipHash halfsiphash.c SIPROUND
ALTERED = (6, 16, 9, 11, 13, 16)   # one set drawn from the U2 pool (passes avalanche.py)


def sipround(r):
    a, b, c, d, e, f = r
    return [
        "v0 += v1",
        f"v1 = bit32.bxor(bit32.lrotate(v1, {a}), v0)",
        f"v0 = bit32.lrotate(v0, {b})",
        "v2 += v3",
        f"v3 = bit32.bxor(bit32.lrotate(v3, {c}), v2)",
        "v0 += v3",
        f"v3 = bit32.bxor(bit32.lrotate(v3, {d}), v0)",
        "v2 += v1",
        f"v1 = bit32.bxor(bit32.lrotate(v1, {e}), v2)",
        f"v2 = bit32.lrotate(v2, {f})",
    ]


def emit(c, d, name, rot):
    rounds_c = "\n".join("\t\t" + s for _ in range(c) for s in sipround(rot))
    rounds_c_tail = "\n".join("\t" + s for _ in range(c) for s in sipround(rot))
    rounds_d = "\n".join("\t" + s for _ in range(d) for s in sipround(rot))
    src = f"""--!strict
-- Generated by gen_tag.py: HalfSipHash-{c}-{d}, 4-byte output, rotations {rot}.
return function(k0: number, k1: number, msg: buffer, length: number): number
	local v0, v1 = k0, k1
	local v2 = bit32.bxor(0x6c796765, k0)
	local v3 = bit32.bxor(0x74656462, k1)
	local left = length % 4
	local stop = length - left
	for at = 0, stop - 1, 4 do
		local m = buffer.readu32(msg, at)
		v3 = bit32.bxor(v3, m)
{rounds_c}
		v0 = bit32.bxor(v0, m)
	end
	local last = bit32.lshift(length % 256, 24)
	for i = 0, left - 1 do
		last = bit32.bor(last, bit32.lshift(buffer.readu8(msg, stop + i), 8 * i))
	end
	v3 = bit32.bxor(v3, last)
{rounds_c_tail}
	v0 = bit32.bxor(v0, last)
	v2 = bit32.bxor(v2, 0xff)
{rounds_d}
	return bit32.bxor(v1, v3)
end
"""
    path = os.path.join(HERE, f"tag_{c}{d}_{name}.luau")
    with open(path, "w") as fh:
        fh.write(src)


for c, d in [(1, 3), (2, 3), (1, 4), (2, 4), (3, 4), (4, 4)]:
    emit(c, d, "ref", REFERENCE)
emit(1, 3, "alt", ALTERED)
emit(2, 4, "alt", ALTERED)

"""Writes studio/Samples.luau: realistic frames (hex) plus Python zstd sizes per level,
so the Studio probe can (a) measure the engine's on-wire size of real frames and
(b) fingerprint the engine's zstd level against EncodingService and libzstd.

Usage: PYTHONPATH=<zstandard dir> python3 export_samples.py
"""
import os

import traffic
from layouts import Layout
from wire import zstd_len

LEVELS = [-7, -5, -3, -1, 1, 2, 3, 4, 5, 6, 7, 9, 12, 19]


def frame(model, kw, layout, idx, age=1):
    m = traffic.MODELS[model](seed=7, **kw)
    fr = [m.step() for _ in range(idx + 1)]
    return getattr(Layout(m), layout)(fr, idx, age)


def main():
    samples = [
        ("shooter60 dlt_col_varint", frame("shooter", dict(hz=60), "dlt_col_varint", 40)),
        ("shooter60 hyb_pred_varint", frame("shooter", dict(hz=60), "hyb_pred_varint", 40)),
        ("shooter60 col_bits_pred", frame("shooter", dict(hz=60), "col_bits_pred", 40)),
        ("shooter20 abs_row_aligned", frame("shooter", dict(hz=20), "abs_row_aligned", 40)),
        ("racing60 dlt_col_varint", frame("racing", dict(hz=60), "dlt_col_varint", 40)),
        ("mmo20 abs_col_split", frame("mmo", dict(hz=20), "abs_col_split", 40)),
        ("mmo20 dlt_row_fixed", frame("mmo", dict(hz=20), "dlt_row_fixed", 40)),
        ("tycoon10 dlt_col_varint", frame("tycoon", dict(hz=10), "dlt_col_varint", 40)),
        ("tycoon10 xor_row_aligned", frame("tycoon", dict(hz=10), "xor_row_aligned", 40)),
    ]
    text = (" ".join(traffic.ITEMS[:40]) + " " + " ".join(traffic.NAMES)).encode()[:600]
    samples.append(("text 600 B (item and player names)", text))
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "studio", "Samples.luau")
    lines = ["--!strict", "-- Generated by ../export_samples.py. Do not edit.",
             "-- Each sample: name, hex bytes, and libzstd 1.5.7 frame sizes per level",
             "-- (python-zstandard 0.25, checksum off, content size on).", "",
             "export type Sample = { name: string, hex: string, py: { [number]: number } }", "",
             "local samples: { Sample } = {"]
    for name, b in samples:
        py = ", ".join(f"[{lv}] = {zstd_len(b, lv)}" for lv in LEVELS)
        lines.append(f'\t{{ name = "{name}", hex = "{b.hex()}", py = {{ {py} }} }},')
    lines += ["}", "", "return samples", ""]
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    for name, b in samples:
        print(f"{name:38s} {len(b):5d} B  zstd1 {zstd_len(b, 1):5d}  zstd3 {zstd_len(b, 3):5d}  zstd19 {zstd_len(b, 19):5d}")
    print("wrote", out)


if __name__ == "__main__":
    main()

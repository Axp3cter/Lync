"""Writes gen_decoders.luau: the upstream frame decoder a build would generate for decode_shapes.luau's schema.

What "generated" means here (research/generation-methods.md G1/G2, codecs-in-scripts.md W3): per definition,
straight-line reads at a running bit cursor kept in upvalues, field names and bounds as constants, one table
constructor per message, and no codec-kind dispatch. Shared helpers (EG-0, the column reader) are plain local
functions taking constants. Decoded messages go to two flat arrays (definition index, value) instead of one
record table per message. Same rules as the milestone decoder for these shapes (v5.md §4.8: 2, 3, 4, 6, 7, 10);
decode_shapes.luau checks that it returns the milestone decoder's values on every frame it times.

Run: python3 -I gen.py   (writes gen_decoders.luau next to this file)
"""
import os

BOOLS = [f"b{i:02d}" for i in range(1, 33)]

HEAD = r'''--!optimize 2
--!nocheck
-- GENERATED by gen.py: the build's upstream decoder for decode_shapes.luau's schema (see gen.py's docstring).
local readbits = buffer.readbits
local readstring = buffer.readstring
local countrz = bit32.countrz

local G = {}

local B: buffer = buffer.create(0)
local P = 0 -- bit cursor
local S = 0 -- tail cursor, in bits (moves down as tail values are read)
local BUDGET = 0
local DEFS: { number } = {}
local VALS: { any } = {}
local N = 0

local function u(w: number): number?
	local p = P
	local q = p + w
	if q > S then return nil end
	P = q
	return readbits(B, p, w)
end

-- EG-0; nil on running out (rule 4) or a code of 32+ zero bits (past every count and code here: rule 2)
local function eg0(): (number?, number)
	local p = P
	local avail = S - p
	if avail <= 0 then return nil, 4 end
	local win = readbits(B, p, if avail < 32 then avail else 32)
	if win == 0 then return nil, if avail < 32 then 4 else 2 end
	local z = countrz(win)
	local q = p + 2 * z + 1
	if q > S then return nil, 4 end
	P = q
	if z == 0 then return 0, 0 end
	return 2 ^ z - 1 + readbits(B, p + z + 1, z), 0
end

local RES: { number } = {}

-- One integer column of `count` codes in [0, n - 1] into out[1..count] (v5.md §4.3; wire/column.luau's format)
local function col(count: number, n: number, out: { number }): number
	local mode = u(2)
	if mode == nil then return 4 end
	local maxCode = n - 1
	local res = RES
	if mode == 0 then
		for i = 1, count do out[i] = 0 end
		return 0
	elseif mode == 3 then
		local base, rule = eg0()
		if base == nil then return rule end
		local width = u(6)
		if width == nil then return 4 end
		if width > 53 then return 2 end
		if width <= 32 then
			for i = 1, count do
				local p = P
				local q = p + width
				if q > S then return 4 end
				P = q
				local v = base + readbits(B, p, width)
				if v > maxCode then return 2 end
				res[i] = v
			end
		else
			for i = 1, count do
				local lo = u(32)
				local hi = u(width - 32)
				if lo == nil or hi == nil then return 4 end
				local v = base + lo + hi * 4294967296
				if v > maxCode then return 2 end
				res[i] = v
			end
		end
	elseif mode == 1 then
		local k = u(4)
		if k == nil then return 4 end
		local scale = 2 ^ k
		for i = 1, count do
			local q, rule = eg0()
			if q == nil then return rule end
			local r = u(k)
			if r == nil then return 4 end
			local v = q * scale + r
			if v > maxCode then return 2 end
			res[i] = v
		end
	else
		local k = u(4)
		if k == nil then return 4 end
		local scale = 2 ^ k
		local m, rule = eg0()
		if m == nil then return rule end
		if m > count then return 2 end
		for i = 1, count do res[i] = 0 end
		local row = 0
		for _ = 1, m do
			local gap, gapRule = eg0()
			if gap == nil then return gapRule end
			if gap > count - row - 1 then return 2 end
			row += gap + 1
			local q, qRule = eg0()
			if q == nil then return qRule end
			local r = u(k)
			if r == nil then return 4 end
			local v = q * scale + r
			if v > maxCode - 1 then return 2 end
			res[row] = v + 1
		end
	end
	local top = n - 1
	local previous = 0
	for i = 1, count do
		local z = res[i]
		local residual = if z % 2 == 0 then z / 2 else -(z + 1) / 2
		local code
		if residual > top - previous then
			code = previous + (residual - n)
		elseif residual < -previous then
			code = previous + (residual + n)
		else
			code = previous + residual
		end
		out[i] = code
		previous = code
	end
	return 0
end

local function push(def: number, value: any)
	local n = N + 1
	N = n
	DEFS[n] = def
	VALS[n] = value
end

local E_XYZ = { "x", "y", "z" }
local E_ITEM = { "sword", "bow", "staff" }
local CA, CB, CC, CD, CE, CF = {}, {}, {}, {}, {}, {}
'''

# def indices (constants the build assigns): 1 move6 (unreliable), 2 move6r (reliable), 3 sm, 4 bools32, 5 ping1, 6 ping2
MOVE6 = r'''
local function move6Rows(def: number, count: number): number
	for _ = 1, count do
		local p = P
		if p + 42 > S then return 4 end
		P = p + 42
		local a = readbits(B, p, 10)
		local b = readbits(B, p + 10, 10)
		local c = readbits(B, p + 20, 1)
		local d = readbits(B, p + 21, 11)
		local e = readbits(B, p + 32, 2)
		local f = readbits(B, p + 34, 8)
		if a > 1000 or b > 1000 then return 3 end
		if d > 1024 or e > 2 then return 2 end
		push(def, { a = a, b = b, c = c == 1, d = math.min(d * (1 / 1024), 1), e = E_XYZ[e + 1], f = f })
	end
	return 0
end

local function move6Columns(def: number, count: number): number
	local rule = col(count, 1001, CA)
	if rule ~= 0 then return rule end
	rule = col(count, 1001, CB)
	if rule ~= 0 then return rule end
	rule = col(count, 2, CC)
	if rule ~= 0 then return rule end
	rule = col(count, 1025, CD)
	if rule ~= 0 then return rule end
	rule = col(count, 3, CE)
	if rule ~= 0 then return rule end
	rule = col(count, 256, CF)
	if rule ~= 0 then return rule end
	for i = 1, count do
		push(def, { a = CA[i], b = CB[i], c = CC[i] == 1, d = math.min(CD[i] * (1 / 1024), 1), e = E_XYZ[CE[i] + 1], f = CF[i] })
	end
	return 0
end

local function move6(def: number, count: number): number
	if count >= 3 then return move6Columns(def, count) end
	return move6Rows(def, count)
end
'''

SM = r'''
local function sm(def: number, count: number): number
	if count >= 3 then error("generated sm: column form not generated for this probe") end
	for _ = 1, count do
		local item = u(2)
		local length = u(6)
		if item == nil or length == nil then return 4 end
		if item > 2 or length > 32 then return 2 end
		local start = S // 8 - length
		if start < (P + 7) // 8 then return 4 end
		S = start * 8
		local name = readstring(B, start, length)
		local qty = u(7)
		local present = u(1)
		if qty == nil or present == nil then return 4 end
		if qty + 1 > 99 then return 3 end
		local slot = nil
		if present == 1 then
			slot = u(4)
			if slot == nil then return 4 end
		end
		push(def, { item = E_ITEM[item + 1], name = name, qty = qty + 1, slot = slot })
	end
	return 0
end
'''


def bools32():
    lines = ["", "local BC = {}", "for i = 1, 32 do BC[i] = {} end", "",
             "local function bools32(def: number, count: number): number",
             '\tif count < 3 then error("generated bools32: row form not generated for this probe") end']
    for i in range(32):
        lines.append(f"\tlocal c{i + 1} = BC[{i + 1}]")
    for i in range(32):
        lines.append(f"\tdo local rule = col(count, 2, c{i + 1}) if rule ~= 0 then return rule end end")
    fields = ", ".join(f"{name} = c{i + 1}[i] == 1" for i, name in enumerate(BOOLS))
    lines.append("\tfor i = 1, count do")
    lines.append(f"\t\tpush(def, {{ {fields} }})")
    lines.append("\tend")
    lines.append("\treturn 0")
    lines.append("end")
    return "\n".join(lines) + "\n"


TAIL = r'''
local function ping(def: number, count: number): number
	for _ = 1, count do push(def, nil) end
	return 0
end

local DECODE = { move6, move6, sm, bools32, ping, ping }
local UNRELIABLE = { true, false, false, false, false, false }

--[=[
	Decodes one tagged upstream frame (tag not checked here; the tag is claim 2).
	@param buf       the frame, ending in its 2-byte tag (the milestone build's width)
	@param lane      0 reliable, 1 unreliable
	@param wireToDef definition index by wire id + 1 (the session's permutation)
	@param idWidth   the namespace's up-id width
	@param budget    the element allowance
	@return rule (0 accepted), messages decoded, elements used; messages in G.defs / G.values at 1..n
]=]
function G.decodeUp(buf: buffer, lane: number, wireToDef: { number }, idWidth: number, budget: number): (number, number, number)
	local len = buffer.len(buf)
	if lane == 1 and len > 1000 then return 8, 0, 0 end
	if lane == 0 and len > 16384 then return 8, 0, 0 end
	if len < 2 then return 4, 0, 0 end
	B = buf
	P = 0
	S = (len - 2) * 8
	N = 0
	BUDGET = budget
	if lane == 1 then
		if u(12) == nil then return 4, 0, 0 end
	end
	local hasAck = u(1)
	if hasAck == nil then return 4, 0, 0 end
	if hasAck == 1 then
		if u(12) == nil or u(16) == nil then return 4, 0, 0 end
	end
	local segments, rule = eg0()
	if segments == nil then return rule, 0, 0 end
	local isUnreliable = lane == 1
	local previousNs = -1
	-- segments are read and walked in one pass: the toc precedes every chunk, so it is read first
	local nsList, countList = table.create(segments), table.create(segments)
	for i = 1, segments do
		local ns, nsRule = eg0()
		if ns == nil then return nsRule, 0, 0 end
		local c, cRule = eg0()
		if c == nil then return cRule, 0, 0 end
		if ns == previousNs then return 6, 0, 0 end
		previousNs = ns
		nsList[i] = ns
		countList[i] = c + 1
	end
	for i = 1, segments do
		if nsList[i] ~= 1 then return 7, 0, 0 end -- only namespace 1 is welcomed; control chunks are not generated here
		for _ = 1, countList[i] do
			local id = u(idWidth)
			if id == nil then return 4, 0, 0 end
			local def = wireToDef[id + 1]
			if def == nil or UNRELIABLE[def] ~= isUnreliable then return 7, 0, 0 end
			local countLessOne, countRule = eg0()
			if countLessOne == nil then return countRule, 0, 0 end
			local count = countLessOne + 1
			BUDGET -= count
			if BUDGET < 0 then return 10, N, budget - BUDGET end
			local runRule = DECODE[def](def, count)
			if runRule ~= 0 then return runRule, N, budget - BUDGET end
		end
	end
	-- rule 4: bits end exactly at the tail cursor with zero padding
	local p = P
	if (p + 7) // 8 * 8 ~= S then return 4, N, budget - BUDGET end
	local pad = (8 - p % 8) % 8
	if pad > 0 and readbits(B, p, pad) ~= 0 then return 4, N, budget - BUDGET end
	return 0, N, budget - BUDGET
end

G.defs = DEFS
G.values = VALS

return G
'''

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "gen_decoders.luau")
with open(out, "w") as f:
    f.write(HEAD + MOVE6 + SM + bools32() + TAIL)
print("wrote", out)

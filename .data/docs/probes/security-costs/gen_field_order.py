"""Emit field_order_gen.luau: what a build could generate for one record under per-build, per-session and
per-player field orders. Stand-in for the Lync codegen (claim 1 of RESULTS.md).

Record (v5 single-row encoding, LSB-first bits, fields in the chosen order):
  crit   t.bool()                      w = 1
  damage t.int(0, 100)                 w = 7
  target t.int(1, 2^16)                w = 16 (v - 1)
  x,y,z  t.number(-2048, 2048, 1/32)   w = 18 each (n = 131072 codes + 1)
78 bits per row.

Emitted:
  encAcc_<k>(W, v)   straight-line accumulator encoder for order k (k = 0 is name order, seed 0)
  decPos_<k>(b, p)   straight-line decoder for order k, returns the bit position after the row
  encVariants, decVariants: arrays of the P orders (a per-session or per-player pool)
  makeRmw(o1..o6)     closure factory: straight-line read-modify-write encoder whose per-field bit offsets
                      are upvalues fixed per session (any of the 720 orders, no pool needed)
  makeDec(o1..o6)     the matching decoder factory
  encRmw_0            the same RMW encoder with seed-0 offsets as constants (fair baseline for makeRmw)
Run: python3 -I gen_field_order.py   (writes next to this file)
"""
import itertools, os, random

FIELDS = [  # name order (seed 0)
    ("crit", 1, "if v.crit then 1 else 0"),
    ("damage", 7, "v.damage"),
    ("target", 16, "v.target - 1"),
    ("x", 18, "q18(v.x)"),
    ("y", 18, "q18(v.y)"),
    ("z", 18, "q18(v.z)"),
]
P = 16
rng = random.Random(20261015)
orders = [list(range(6))]
while len(orders) < P:
    o = list(range(6)); rng.shuffle(o)
    if o not in orders:
        orders.append(o)

out = []
w = out.append
w("--!strict\n--!optimize 2\n-- GENERATED by gen_field_order.py; do not edit.")
w("local bor, lshift, rshift, band = bit32.bor, bit32.lshift, bit32.rshift, bit32.band")
w("local readu32, writeu32 = buffer.readu32, buffer.writeu32")
w("export type W = { b: buffer, pos: number, acc: number, n: number }")
w("export type Rec = { crit: boolean, damage: number, target: number, x: number, y: number, z: number }")
w("local function q18(x: number): number\n\tlocal q = (x + 2048) * 32 + 0.5\n\tq -= q % 1\n\tif q > 131072 then q = 131072 end\n\treturn q\nend")
w("local M = {}")

for k, order in enumerate(orders):
    w(f"-- order {k}: " + ", ".join(FIELDS[i][0] for i in order))
    w(f"local function encAcc_{k}(W: W, v: Rec)")
    w("\tlocal b, pos, acc, n = W.b, W.pos, W.acc, W.n")
    for i in order:
        name, width, expr = FIELDS[i]
        w(f"\tlocal q_{name} = {expr}")
        w(f"\tacc = bor(acc, lshift(q_{name}, n)); n += {width}")
        w(f"\tif n >= 32 then writeu32(b, pos, acc); pos += 4; n -= 32; acc = if n > 0 then rshift(q_{name}, {width} - n) else 0 end")
    w("\tW.pos, W.acc, W.n = pos, acc, n")
    w("end")
    w(f"local function decPos_{k}(b: buffer, p: number, r: Rec): number")
    off = 0
    for i in order:
        name, width, _ = FIELDS[i]
        w(f"\tdo local o = p + {off}; local q = band(rshift(readu32(b, o // 8), o % 8), {(1 << width) - 1})")
        if name == "crit":
            w("\t\tr.crit = q == 1 end")
        elif name == "damage":
            w("\t\tif q > 100 then return -1 end; r.damage = q end")
        elif name == "target":
            w("\t\tr.target = q + 1 end")
        else:
            w(f"\t\tif q > 131072 then return -1 end; r.{name} = q / 32 - 2048 end")
        off += width
    w(f"\treturn p + {off}")
    w("end")
w("M.encVariants = { " + ", ".join(f"encAcc_{k}" for k in range(P)) + " }")
w("M.decVariants = { " + ", ".join(f"decPos_{k}" for k in range(P)) + " }")
w("M.encAcc_0, M.encAcc_1, M.decPos_0, M.decPos_1 = encAcc_0, encAcc_1, decPos_0, decPos_1")

# RMW with per-session offsets (closure factory) and its constant-offset seed-0 twin
def rmw_body(offs):
    lines = []
    for i, (name, width, expr) in enumerate(FIELDS):
        lines.append(f"\tdo local o = p + {offs[i]}; local by = o // 8")
        lines.append(f"\t\twriteu32(b, by, bor(readu32(b, by), lshift({expr}, o % 8))) end")
    return lines

seed0_offs = []
acc_off = 0
for name, width, _ in FIELDS:
    seed0_offs.append(acc_off); acc_off += width
w("-- seed-0 offsets as constants")
w("function M.encRmw_0(b: buffer, p: number, v: Rec): number")
out.extend(rmw_body([str(o) for o in seed0_offs]))
w("\treturn p + 78\nend")
w("-- per-session offsets as upvalues: one closure per session")
w("function M.makeRmw(o1: number, o2: number, o3: number, o4: number, o5: number, o6: number): (buffer, number, Rec) -> number")
w("\treturn function(b: buffer, p: number, v: Rec): number")
out.extend("\t" + l for l in rmw_body(["o1", "o2", "o3", "o4", "o5", "o6"]))
w("\t\treturn p + 78\n\tend\nend")
w("function M.makeDec(o1: number, o2: number, o3: number, o4: number, o5: number, o6: number): (buffer, number, Rec) -> number")
w("\treturn function(b: buffer, p: number, r: Rec): number")
for i, (name, width, _) in enumerate(FIELDS):
    w(f"\t\tdo local o = p + o{i + 1}; local q = band(rshift(readu32(b, o // 8), o % 8), {(1 << width) - 1})")
    if name == "crit":
        w("\t\t\tr.crit = q == 1 end")
    elif name == "damage":
        w("\t\t\tif q > 100 then return -1 end; r.damage = q end")
    elif name == "target":
        w("\t\t\tr.target = q + 1 end")
    else:
        w(f"\t\t\tif q > 131072 then return -1 end; r.{name} = q / 32 - 2048 end")
w("\t\treturn p + 78\n\tend\nend")
w("M.orders = { " + ", ".join("{ " + ", ".join(str(i + 1) for i in o) + " }" for o in orders) + " }")
w("M.widths = { " + ", ".join(str(f[1]) for f in FIELDS) + " }")
w("return M")

here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "field_order_gen.luau"), "w").write("\n".join(out) + "\n")
print(f"wrote field_order_gen.luau: {P} orders")
